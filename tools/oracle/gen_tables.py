#!/usr/bin/env python3
"""Convert python-validity's lookup tables to Rust, mechanically.

Usage: gen_tables.py <path-to-python-validity> > crates/validity-proto/src/tables/generated.rs
       then run `cargo fmt`.

Sources: validitysensor/hw_tables.py (device names, flash ICs) and
validitysensor/generated_tables.py (sensor types, capture programs). These are lookup
tables and register/timeslot programs, not signed vendor data: every capture program
splits into typed chunks and every timeslot table disassembles (checked below).
"""
import sys

sys.path.insert(0, sys.argv[1])

from validitysensor import hw_tables as H  # noqa: E402
from validitysensor import timeslot as prg  # noqa: E402
from validitysensor.table_types import SensorTypeInfo, SensorCaptureProg  # noqa: E402
import validitysensor.generated_tables  # noqa: E402,F401


def hexlit(b, indent):
    """A hex string literal, split in 64-byte lines inside concat!()."""
    h = b.hex()
    if len(h) <= 128:
        return '"%s"' % h
    parts = [h[i:i + 128] for i in range(0, len(h), 128)]
    pad = ' ' * indent
    return 'concat!(\n%s' % ''.join('%s    "%s",\n' % (pad, p) for p in parts) + pad + ')'


def check_program(blob):
    total = 0
    for t, v in prg.split_chunks(blob):
        total += 4 + len(v)
        if t == 0x34:
            b = v
            while b:
                _, sz, *_ = prg.decode_insn(b)
                assert sz <= len(b), 'truncated timeslot instruction'
                b = b[sz:]
    assert total == len(blob), 'trailing bytes in program'


out = []
w = out.append
w('//! Generated by `tools/oracle/gen_tables.py` from python-validity v0.15')
w('//! (`hw_tables.py`, `generated_tables.py`). Do not edit by hand.')
w('')
w('use super::{DeviceInfo, FlashIcInfo, SensorCaptureProg, SensorTypeInfo};')
w('')
w('pub const DEV_INFO: &[DeviceInfo] = &[')
for d in H.dev_info_table:
    w('    DeviceInfo { major: 0x%04x, sensor_type: 0x%04x, version: 0x%02x, version_mask: 0x%02x, name: "%s" },'
      % (d.major, d.type, d.version, d.version_mask, d.name.replace('\\', '\\\\').replace('"', '\\"')))
w('];')
w('')
w('pub const FLASH_IC: &[FlashIcInfo] = &[')
for f in H.flash_ic_table:
    w('    FlashIcInfo { name: "%s", size: %d, f18: 0x%x, jid0: 0x%x, jid1: 0x%x, f1b: 0x%x, f1c: 0x%x, '
      'f1e: 0x%x, sector_size: 0x%x, sector_erase_cmd: 0x%x, f25: 0x%x, f26: 0x%x },'
      % (f.name, f.size, f.f18, f.jid0, f.jid1, f.f1b, f.f1c, f.f1e, f.secror_size, f.sector_erase_cmd,
         f.f25, f.f26))
w('];')
w('')
w('pub const SENSOR_TYPES: &[SensorTypeInfo] = &[')
for t in SensorTypeInfo.table:
    w('    SensorTypeInfo {')
    w('        sensor_type: 0x%04x,' % t.sensor_type)
    w('        bytes_per_line: 0x%x,' % t.bytes_per_line)
    w('        repeat_multiplier: %d,' % t.repeat_multiplier)
    w('        lines_per_calibration_data: %d,' % t.lines_per_calibration_data)
    w('        line_width: %d,' % t.line_width)
    w('        calibration_blob: %s,' % hexlit(t.calibration_blob, 8))
    w('    },')
w('];')
w('')
w('pub const CAPTURE_PROGRAMS: &[SensorCaptureProg] = &[')
for p in SensorCaptureProg.table:
    check_program(b''.join(p.blobs))
    w('    SensorCaptureProg {')
    for k in ('major', 'minor', 'build', 'u1', 'dev_type', 'a0', 'a1'):
        w('        %s: 0x%x,' % (k, getattr(p, k)))
    w('        blobs: &[')
    for b in p.blobs:
        w('            %s,' % hexlit(b, 12))
    w('        ],')
    w('    },')
w('];')
print('\n'.join(out))
